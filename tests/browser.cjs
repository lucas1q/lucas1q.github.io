'use strict';
// Run: node tests/browser.cjs (requires Playwright and Chromium).
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const { chromium } = require('playwright');
const JSZip = require('../vendor/jszip-3.10.2.min.js');
const root = path.resolve(__dirname, '..');
const KEY = 'course-schedule.local.v1';
const mime = { '.html': 'text/html', '.js': 'application/javascript', '.css': 'text/css' };
const server = http.createServer((req, res) => {
    const filename = path.join(root, req.url === '/' ? 'index.html' : req.url);
    if (!filename.startsWith(root + path.sep) || !fs.existsSync(filename) || !fs.statSync(filename).isFile()) { res.writeHead(404).end(); return; }
    res.setHeader('Content-Type', mime[path.extname(filename)] || 'application/octet-stream');
    res.end(fs.readFileSync(filename));
});
(async () => {
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const origin = `http://127.0.0.1:${server.address().port}`;
    const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
    let count = 0;
    const pass = name => { count++; console.log(`PASS ${name}`); };
    try {
        const context = await browser.newContext({ timezoneId: 'America/Los_Angeles', acceptDownloads: true });
        const page = await context.newPage();
        const errors = [], external = [];
        page.on('pageerror', error => errors.push(error.message));
        page.on('request', req => { if (!req.url().startsWith(origin)) external.push(req.url()); });
        await page.goto(origin);
        await page.waitForSelector('#connectionStatus');
        assert.match(await page.locator('#connectionStatus').textContent(), /本地模式/);
        assert.match(await page.locator('#securityNotice').textContent(), /已暂停/);
        pass('boot in explicit local-only mode with no external requests');
        const payload = '<img src=x onerror="window.xss=1"><svg onload="window.xss=2">';
        await page.locator('#studentName').fill(payload);
        await page.locator('#classDay').selectOption('1');
        await page.locator('#classStartTime').fill('09:00');
        await page.locator('#classEndTime').fill('10:00');
        await page.locator('#addClass').click();
        await page.locator('#selectedDate').fill('2026-10-05');
        await page.locator('#selectedTime').fill('09:30');
        for (const id of ['classList', 'todayOverview', 'currentClassContainer']) {
            assert.equal(await page.locator(`#${id} .course-name`).textContent(), payload);
            assert.equal(await page.locator(`#${id} img, #${id} svg`).count(), 0);
        }
        assert.equal(await page.evaluate(() => window.xss), undefined);
        pass('malicious manual names stay text in all three course views; local weekday works');
        await page.reload();
        assert.equal(await page.locator('#classList .course-name').textContent(), payload);
        pass('local courses persist after reload');
        await page.locator('#selectedDate').fill('2026-10-05');
        await page.locator('#selectedTime').fill('10:00');
        assert.match(await page.locator('#currentClassContainer').textContent(), /没有人上课/);
        pass('end time is exclusive');
        await page.locator('#recognizedText').fill('张三 周天 9:00-10:00\n李四 周二 11:00-12:00\n王五 周三 13:00-14:00\n坏数据 周一 29:00-30:00');
        await page.locator('#parseText').click();
        assert.equal(await page.locator('.course-item').count(), 3);
        assert.equal(await page.locator('.course-day').first().inputValue(), '0');
        await page.locator('.remove-course').nth(0).click();
        await page.locator('.remove-course').nth(1).click();
        assert.equal(await page.locator('.course-item').count(), 1);
        await page.locator('.student-name').fill(payload);
        assert.equal(await page.locator('#parsedCourses img').count(), 0);
        await page.locator('#saveParsedCourses').click();
        assert.equal(await page.locator('#classList .course-name').count(), 2);
        pass('text parsing, Sunday mapping, editing and repeated preview removal');
        const before = await page.evaluate(key => localStorage.getItem(key), KEY);
        await page.locator('#recognizedText').fill('张三 周一 09:00-10:00\n李四 周二 11:00-12:00');
        await page.locator('#parseText').click();
        await page.locator('.student-name').nth(1).fill('');
        await page.locator('#saveParsedCourses').click();
        assert.equal(await page.evaluate(key => localStorage.getItem(key), KEY), before);
        assert.match(await page.locator('#appMessage').textContent(), /未保存任何课程/);
        pass('invalid batch saves fail atomically and retain edits');
        const upload = async (name, buffer, type='application/octet-stream') => {
            await page.locator('#fileUpload').setInputFiles({ name, mimeType:type, buffer: Buffer.isBuffer(buffer) ? buffer : Buffer.from(buffer) });
            await page.locator('#startRecognition').click();
            await page.waitForFunction(() => !document.getElementById('fileUpload').disabled);
        };
        const evil = {student_name: '\"><img src=x onerror="window.xss=3">',day:'0',start_time:'10:00',end_time:'11:00'};
        await upload('backup.json', JSON.stringify({schemaVersion:1,courses:[evil]}), 'application/json');
        assert.equal(await page.locator('.student-name').inputValue(), evil.student_name);
        assert.equal(await page.locator('#parsedCourses img').count(), 0);
        await page.locator('#saveParsedCourses').click();
        assert.equal(await page.locator('#classList .course-name').count(), 3);
        pass('JSON import uses safe value assignment and appends only after review');
        await upload('bad.json', JSON.stringify([evil,{...evil,day:'0junk'}]), 'application/json');
        assert.match(await page.locator('#appMessage').textContent(), /读取失败/);
        assert.equal(await page.locator('#classList .course-name').count(), 3);
        await upload('bad.json', '{bad json', 'application/json');
        assert.match(await page.locator('#appMessage').textContent(), /读取失败/);
        pass('malformed JSON and invalid fields rejected without changing courses');
        await upload('schedule.txt', '赵六 周四 14:00-15:00', 'text/plain');
        assert.equal(await page.locator('#recognizedText').inputValue(), '赵六 周四 14:00-15:00');
        pass('UTF-8 TXT imported locally');
        const zip = new JSZip();
        zip.file('word/document.xml','<?xml version="1.0"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>张三 周一 09:00-10:00</w:t></w:r></w:p><w:tbl><w:tr><w:tc><w:p><w:r><w:t>李四</w:t></w:r></w:p></w:tc><w:tc><w:p><w:r><w:t>周二</w:t></w:r></w:p></w:tc><w:tc><w:p><w:r><w:t>11:00-12:00</w:t></w:r></w:p></w:tc></w:tr></w:tbl></w:body></w:document>');
        await upload('schedule.docx', await zip.generateAsync({type:'nodebuffer',compression:'DEFLATE'}));
        assert.equal(await page.locator('#recognizedText').inputValue(), '张三 周一 09:00-10:00\n李四 周二 11:00-12:00');
        await page.locator('#parseText').click();
        assert.equal(await page.locator('.course-item').count(), 2);
        pass('DOCX paragraphs and table rows remain local and parse without duplication');
        zip.file('word/document.xml','<?xml version="1.0"?><!DOCTYPE foo [<!ENTITY xxe SYSTEM "https://example.invalid/private">]><foo>&xxe;</foo>');
        await upload('entities.docx', await zip.generateAsync({type:'nodebuffer'}));
        assert.match(await page.locator('#appMessage').textContent(), /外部实体/);
        zip.file('word/document.xml','x'.repeat(2*1024*1024+1));
        await upload('large.docx', await zip.generateAsync({type:'nodebuffer',compression:'DEFLATE'}));
        assert.match(await page.locator('#appMessage').textContent(), /正文过大/);
        await upload('picture.png', 'not-an-image', 'image/png');
        assert.match(await page.locator('#appMessage').textContent(), /当前已停用/);
        pass('entity documents, oversized expanded XML and disabled OCR formats fail closed');
        const downloadPromise = page.waitForEvent('download');
        await page.locator('#exportCourses').click();
        const download = await downloadPromise;
        assert.equal(download.suggestedFilename(), 'course-schedule-backup.json');
        const exported = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
        assert.equal(exported.schemaVersion, 1);
        assert.equal(exported.courses.length, 3);
        assert.equal(exported.courses[0].student_name, payload);
        pass('JSON backup round-trips literal malicious text and all saved records');
        const second = await context.newPage();
        await second.goto(origin);
        await second.locator('#studentName').fill('另一个标签页');
        await second.locator('#classStartTime').fill('15:00');
        await second.locator('#classEndTime').fill('16:00');
        await second.locator('#addClass').click();
        await page.waitForFunction(() => document.querySelectorAll('#classList .course-name').length === 4);
        await second.close();
        pass('storage changes in another tab refresh visible courses');
        await page.setViewportSize({width:390,height:844});
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        await page.screenshot({path:'/tmp/course-site-mobile.png',fullPage:true});
        await page.setViewportSize({width:1280,height:900});
        await page.screenshot({path:'/tmp/course-site-desktop.png',fullPage:true});
        pass('mobile layout does not overflow horizontally');
        assert.deepEqual(external, []);
        assert.deepEqual(errors, []);
        pass('no external network requests, script execution or browser runtime errors');
        await page.evaluate(key => localStorage.setItem(key, 'broken-json'), KEY);
        await page.reload();
        await page.locator('#studentName').fill('保留输入');
        await page.locator('#classStartTime').fill('09:00');
        await page.locator('#classEndTime').fill('10:00');
        await page.locator('#addClass').click();
        assert.equal(await page.evaluate(key => localStorage.getItem(key), KEY), 'broken-json');
        assert.equal(await page.locator('#studentName').inputValue(), '保留输入');
        pass('corrupt storage is not silently overwritten');
        const blocked = await browser.newContext();
        await blocked.addInitScript(() => { Storage.prototype.setItem = function(){throw new DOMException('blocked', 'QuotaExceededError');}; });
        const blockedPage = await blocked.newPage();
        await blockedPage.goto(origin);
        await blockedPage.locator('#studentName').fill('未保存');
        await blockedPage.locator('#classStartTime').fill('09:00');
        await blockedPage.locator('#classEndTime').fill('10:00');
        await blockedPage.locator('#addClass').click();
        assert.match(await blockedPage.locator('#appMessage').textContent(), /课程未保存/);
        assert.equal(await blockedPage.locator('#classList .course-name').count(), 0);
        pass('storage failures never claim successful saving');
        console.log(`All ${count} browser checks passed.`);
    } finally {
        await browser.close();
        await new Promise(resolve => server.close(resolve));
    }
})().catch(error => { console.error(error); process.exitCode = 1; server.close(); });
